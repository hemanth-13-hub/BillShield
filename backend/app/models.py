"""
SQLAlchemy ORM models for BillShield.

Entity overview
───────────────
Room               Physical hostel room (hostel, block, room number, AC/Non-AC)
Student            One of the 3 roommates assigned to a Room (informational only)
Appliance          An electrical appliance type present in a Room; quantity + rated
                   wattage used for the theoretical consumption estimate
BillingPeriod      A named date range (e.g. "October 2026") that acts as the
                   shared time anchor for both RoomReading and HostelMeterReading —
                   same FK on both sides guarantees period alignment at DB level
RoomReading        Student-entered or simulated meter reading for one billing period
HostelMeterReading Official hostel-side bill for the same billing period
Settings           Singleton row: electricity rate (₹/kWh) and tolerance (%)

Source enum (ReadingSource)
───────────────────────────
Every reading MUST carry exactly one of these labels — never omitted, never faked:
  "Manual Entry"       User keyed in the numbers themselves
  "Simulated Demo Data"  Generated by the backend simulation engine
  "Sensor (Future)"    Reserved for future ESP32 hardware integration
"""

from __future__ import annotations

import enum
from datetime import date, datetime
from typing import Optional
from zoneinfo import ZoneInfo

from sqlalchemy import (
    CheckConstraint,
    Date,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base

IST = ZoneInfo("Asia/Kolkata")


def _now_ist() -> datetime:
    """Return current datetime in IST with explicit timezone info."""
    return datetime.now(tz=IST)


