# Appliance
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class Appliance(Base):
    """
    An electrical appliance *type* present in a Room.
    One row = one appliance type (e.g. "Ceiling Fan").
    quantity      : how many units of this type are in the room
    rated_watts   : manufacturer rated power consumption in Watts
    assumed_daily_hours : assumed hours of operation per day (for theoretical estimate)

    Theoretical daily kWh (used in Verification breakdown) =
        (rated_watts × quantity × assumed_daily_hours) / 1000

    Standard hostel inventory (enforced during seeding):
      AC room    : AC(1×1500W,8h), Fan(2×75W,12h), TubeLight(2×40W,8h),
                   WashroomLight(1×15W,2h), BalconyLight(1×15W,3h)
      Non-AC room: Fan(2×75W,14h), TubeLight(2×40W,8h),
                   WashroomLight(1×15W,2h), BalconyLight(1×15W,3h)
    """

    __tablename__ = "appliances"

    id:                  Mapped[int]   = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:             Mapped[int]   = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    name:                Mapped[str]   = mapped_column(String(80),  nullable=False)
    rated_watts:         Mapped[float] = mapped_column(Float, nullable=False)
    quantity:            Mapped[int]   = mapped_column(Integer, nullable=False, default=1)
    assumed_daily_hours: Mapped[float] = mapped_column(Float, nullable=False)

    # ── Relationships ──────────────────────────────────────────────────────
    room: Mapped[Room] = relationship("Room", back_populates="appliances")

    def __repr__(self) -> str:
        return (
            f"<Appliance id={self.id} name={self.name!r} "
            f"{self.rated_watts}W×{self.quantity} {self.assumed_daily_hours}h/day>"
        )


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# BillingPeriod
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class BillingPeriod(Base):
    """
    A named date range that acts as the shared time anchor for all readings.

    Why a separate entity?
    Both RoomReading and HostelMeterReading carry a FK to the same BillingPeriod.
    This guarantees period alignment at the database level — a RoomReading and its
    corresponding HostelMeterReading are compared only when they share the exact
    same (period_start, period_end), not just overlapping ranges.

    Unique constraint on (period_start, period_end) prevents duplicate periods.
    CHECK constraint ensures end > start.
    """

    __tablename__ = "billing_periods"
    __table_args__ = (
        UniqueConstraint("period_start", "period_end", name="uq_billing_period_range"),
        CheckConstraint("period_end > period_start",    name="ck_period_end_after_start"),
    )

    id:           Mapped[int]      = mapped_column(Integer, primary_key=True, autoincrement=True)
    period_start: Mapped[date]     = mapped_column(Date, nullable=False)
    period_end:   Mapped[date]     = mapped_column(Date, nullable=False)
    label:        Mapped[str]      = mapped_column(String(50), nullable=False)  # e.g. "October 2026"
    created_at:   Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    # ── Relationships ──────────────────────────────────────────────────────
    room_readings: Mapped[list[RoomReading]] = relationship(
        "RoomReading", back_populates="billing_period",
    )
    hostel_meter_readings: Mapped[list[HostelMeterReading]] = relationship(
        "HostelMeterReading", back_populates="billing_period",
    )

    def __repr__(self) -> str:
        return f"<BillingPeriod id={self.id} label={self.label!r} [{self.period_start}→{self.period_end}]>"


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# RoomReading
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class RoomReading(Base):
    """
    Student's electricity meter reading for one billing period.

    Business rules enforced at both Pydantic and DB layers:
      1. reading_end   > reading_start   (no decreasing cumulative readings)
      2. reading_start >= 0              (no negative kWh)
      3. consumption   = end − start     (computed on insert, never editable)
      4. One reading per (room_id, billing_period_id)
      5. source must be a valid ReadingSource value
    """

    __tablename__ = "room_readings"
    __table_args__ = (
        UniqueConstraint(
            "room_id", "billing_period_id",
            name="uq_room_reading_per_period",
        ),
        CheckConstraint("reading_end > reading_start",  name="ck_reading_end_gt_start"),
        CheckConstraint("reading_start >= 0",           name="ck_reading_start_non_negative"),
        CheckConstraint("consumption >= 0",             name="ck_consumption_non_negative"),
    )

    id:                Mapped[int]           = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:           Mapped[int]           = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    billing_period_id: Mapped[int]           = mapped_column(
        Integer, ForeignKey("billing_periods.id"), nullable=False,
    )
    reading_start:     Mapped[float]         = mapped_column(Float, nullable=False)
    reading_end:       Mapped[float]         = mapped_column(Float, nullable=False)
    consumption:       Mapped[float]         = mapped_column(Float, nullable=False)  # = end − start
    source:            Mapped[str]           = mapped_column(String(30), nullable=False)
    notes:             Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    recorded_at:       Mapped[datetime]      = mapped_column(DateTime(timezone=True), default=_now_ist)
    created_at:        Mapped[datetime]      = mapped_column(DateTime(timezone=True), default=_now_ist)

    # ── Relationships ──────────────────────────────────────────────────────
    room: Mapped[Room] = relationship("Room", back_populates="room_readings")
    billing_period: Mapped[BillingPeriod] = relationship(
        "BillingPeriod", back_populates="room_readings",
    )

    def __repr__(self) -> str:
        return (
            f"<RoomReading id={self.id} room={self.room_id} "
            f"period={self.billing_period_id} {self.consumption:.2f}kWh [{self.source}]>"
        )


