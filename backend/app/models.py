# Settings  (singleton row, id=1 always)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class Settings(Base):
    """
    Application-wide settings stored as a singleton row (id always = 1).
    Created by the seed script; updated via PUT /api/v1/settings.

    rate_per_unit      : ₹ per kWh (default ₹10)
    tolerance_percent  : acceptable % deviation before flagging a mismatch (default ±5%)
    """

    __tablename__ = "settings"
    __table_args__ = (
        CheckConstraint("rate_per_unit > 0",      name="ck_rate_positive"),
        CheckConstraint("tolerance_percent > 0",  name="ck_tolerance_positive"),
        CheckConstraint("tolerance_percent <= 100", name="ck_tolerance_max"),
    )

    id:                Mapped[int]      = mapped_column(Integer, primary_key=True, default=1)
    rate_per_unit:     Mapped[float]    = mapped_column(Float, nullable=False, default=10.0)
    tolerance_percent: Mapped[float]    = mapped_column(Float, nullable=False, default=5.0)
    updated_at:        Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    def __repr__(self) -> str:
        return (
            f"<Settings rate=₹{self.rate_per_unit}/kWh "
            f"tolerance=±{self.tolerance_percent}%>"
        )


