# VerificationResult (persisted dual-meter comparison audit per room & period)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class VerificationResult(Base):
    """
    Persisted verification outcome for a paired (RoomReading, HostelMeterReading)
    within a Room and BillingPeriod.
    """

    __tablename__ = "verification_results"
    __table_args__ = (
        UniqueConstraint("room_id", "billing_period_id", name="uq_verification_per_room_period"),
    )

    id:                       Mapped[int]      = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:                  Mapped[int]      = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    billing_period_id:        Mapped[int]      = mapped_column(
        Integer, ForeignKey("billing_periods.id"), nullable=False,
    )
    room_reading_id:          Mapped[int]      = mapped_column(
        Integer, ForeignKey("room_readings.id", ondelete="CASCADE"), nullable=False,
    )
    hostel_meter_reading_id:  Mapped[int]      = mapped_column(
        Integer, ForeignKey("hostel_meter_readings.id", ondelete="CASCADE"), nullable=False,
    )
    room_units:               Mapped[float]    = mapped_column(Float, nullable=False)
    hostel_units:             Mapped[float]    = mapped_column(Float, nullable=False)
    difference_units:         Mapped[float]    = mapped_column(Float, nullable=False)
    difference_percent:       Mapped[float]    = mapped_column(Float, nullable=False)
    rate_per_unit:            Mapped[float]    = mapped_column(Float, nullable=False)
    tolerance_percent:        Mapped[float]    = mapped_column(Float, nullable=False)
    room_bill:                Mapped[float]    = mapped_column(Float, nullable=False)
    hostel_bill:              Mapped[float]    = mapped_column(Float, nullable=False)
    bill_difference_rupees:   Mapped[float]    = mapped_column(Float, nullable=False)
    verdict:                  Mapped[str]      = mapped_column(String(40), nullable=False)
    room_reading_source:      Mapped[str]      = mapped_column(String(30), nullable=False)
    hostel_reading_source:    Mapped[str]      = mapped_column(String(30), nullable=False)
    verified_at:              Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    room: Mapped[Room] = relationship("Room", back_populates="verification_results")
    billing_period: Mapped[BillingPeriod] = relationship("BillingPeriod")
