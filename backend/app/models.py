# HostelMeterReading
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class HostelMeterReading(Base):
    """
    Official hostel-side electricity bill for a room for one billing period.

    billed_units  : kWh charged on the official bill
    billed_amount : ₹ amount on the bill (may differ from units × rate if the
                    hostel applies additional charges)

    Same source-labelling rules as RoomReading apply — the source field is
    mandatory and displayed prominently in the UI and PDF.
    One reading per (room_id, billing_period_id).
    """

    __tablename__ = "hostel_meter_readings"
    __table_args__ = (
        UniqueConstraint(
            "room_id", "billing_period_id",
            name="uq_hostel_reading_per_period",
        ),
        CheckConstraint("billed_units >= 0",  name="ck_billed_units_non_negative"),
        CheckConstraint("billed_amount >= 0", name="ck_billed_amount_non_negative"),
    )

    id:                Mapped[int]             = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:           Mapped[int]             = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    billing_period_id: Mapped[int]             = mapped_column(
        Integer, ForeignKey("billing_periods.id"), nullable=False,
    )
    reading_start:     Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    reading_end:       Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    billed_units:      Mapped[float]           = mapped_column(Float, nullable=False)
    billed_amount:     Mapped[float]           = mapped_column(Float, nullable=False)
    source:            Mapped[str]             = mapped_column(String(30), nullable=False)
    notes:             Mapped[Optional[str]]   = mapped_column(Text, nullable=True)
    recorded_at:       Mapped[datetime]        = mapped_column(DateTime(timezone=True), default=_now_ist)
    created_at:        Mapped[datetime]        = mapped_column(DateTime(timezone=True), default=_now_ist)

    # ── Relationships ──────────────────────────────────────────────────────
    room: Mapped[Room] = relationship("Room", back_populates="hostel_meter_readings")
    billing_period: Mapped[BillingPeriod] = relationship(
        "BillingPeriod", back_populates="hostel_meter_readings",
    )

    def __repr__(self) -> str:
        return (
            f"<HostelMeterReading id={self.id} room={self.room_id} "
            f"period={self.billing_period_id} {self.billed_units}kWh ₹{self.billed_amount} [{self.source}]>"
        )


