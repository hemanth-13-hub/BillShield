# Student
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class Student(Base):
    """
    One of up to 3 roommates in a Room.
    No authentication layer; purely informational metadata used in PDF reports.
    Hostel rule: exactly 3 roommates per room.
    """

    __tablename__ = "students"

    id:          Mapped[int]      = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:     Mapped[int]      = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    name:        Mapped[str]      = mapped_column(String(100), nullable=False)
    roll_number: Mapped[str]      = mapped_column(String(20),  nullable=False, unique=True)
    created_at:  Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    # ── Relationships ──────────────────────────────────────────────────────
    room: Mapped[Room] = relationship("Room", back_populates="students")
    roommate_slot: Mapped[Optional[Roommate]] = relationship(
        "Roommate", back_populates="student", uselist=False, cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<Student id={self.id} roll={self.roll_number!r} name={self.name!r}>"


