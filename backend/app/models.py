# Room
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class Room(Base):
    """
    Physical hostel room.  Identity is (hostel_type, block, room_number).
    All readings, students, and appliances are scoped to this room.
    Deleting a Room cascades to all child records.
    """

    __tablename__ = "rooms"
    __table_args__ = (
        UniqueConstraint(
            "hostel_type", "block", "room_number",
            name="uq_room_identity",
        ),
    )

    id:          Mapped[int]           = mapped_column(Integer, primary_key=True, autoincrement=True)
    block_id:    Mapped[Optional[int]] = mapped_column(
        Integer, ForeignKey("blocks.id", ondelete="SET NULL"), nullable=True,
    )
    hostel_type: Mapped[str]      = mapped_column(String(10), nullable=False)   # HostelType
    block:       Mapped[str]      = mapped_column(String(1),  nullable=False)   # Block A-G
    room_number: Mapped[str]      = mapped_column(String(10), nullable=False)
    room_type:   Mapped[str]      = mapped_column(String(10), nullable=False)   # RoomType
    floor:       Mapped[int]      = mapped_column(Integer,    nullable=False, default=1)
    created_at:  Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    # ── Relationships ──────────────────────────────────────────────────────
    hostel_block: Mapped[Optional[HostelBlock]] = relationship(
        "HostelBlock", back_populates="rooms",
    )
    students: Mapped[list[Student]] = relationship(
        "Student", back_populates="room", cascade="all, delete-orphan",
    )
    roommates: Mapped[list[Roommate]] = relationship(
        "Roommate", back_populates="room", cascade="all, delete-orphan",
    )
    appliances: Mapped[list[Appliance]] = relationship(
        "Appliance", back_populates="room", cascade="all, delete-orphan",
    )
    room_readings: Mapped[list[RoomReading]] = relationship(
        "RoomReading", back_populates="room", cascade="all, delete-orphan",
    )
    hostel_meter_readings: Mapped[list[HostelMeterReading]] = relationship(
        "HostelMeterReading", back_populates="room", cascade="all, delete-orphan",
    )
    verification_results: Mapped[list[VerificationResult]] = relationship(
        "VerificationResult", back_populates="room", cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return (
            f"<Room id={self.id} {self.hostel_type} "
            f"Block-{self.block} #{self.room_number} ({self.room_type})>"
        )


