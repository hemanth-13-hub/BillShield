# HostelCategory & HostelBlock
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class HostelCategory(Base):
    """
    Aditya University hostel category ("boys" or "girls").
    """

    __tablename__ = "hostel_categories"

    id:          Mapped[int]           = mapped_column(Integer, primary_key=True, autoincrement=True)
    code:        Mapped[str]           = mapped_column(String(10), nullable=False, unique=True)
    name:        Mapped[str]           = mapped_column(String(50), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    blocks: Mapped[list[HostelBlock]] = relationship(
        "HostelBlock", back_populates="category", cascade="all, delete-orphan",
    )


class HostelBlock(Base):
    """
    Hostel building block A–G belonging to either Boys or Girls hostel category.
    """

    __tablename__ = "blocks"
    __table_args__ = (
        UniqueConstraint("hostel_category_id", "code", name="uq_block_per_hostel"),
    )

    id:                 Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    hostel_category_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("hostel_categories.id", ondelete="CASCADE"), nullable=False,
    )
    code:               Mapped[str] = mapped_column(String(1), nullable=False)
    name:               Mapped[str] = mapped_column(String(20), nullable=False)

    category: Mapped[HostelCategory] = relationship("HostelCategory", back_populates="blocks")
    rooms: Mapped[list[Room]] = relationship("Room", back_populates="hostel_block")


