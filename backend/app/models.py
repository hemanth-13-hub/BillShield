# Roommate (3 roommates per room capacity slot table)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class Roommate(Base):
    """
    Fixed 3-bed roommate slot allocation linking Student <-> Room (slots 1..3).
    """

    __tablename__ = "roommates"
    __table_args__ = (
        UniqueConstraint("room_id", "slot_number", name="uq_room_slot"),
        UniqueConstraint("student_id", name="uq_roommate_student"),
        CheckConstraint("slot_number >= 1 AND slot_number <= 3", name="ck_roommate_slot_range"),
    )

    id:          Mapped[int]      = mapped_column(Integer, primary_key=True, autoincrement=True)
    room_id:     Mapped[int]      = mapped_column(
        Integer, ForeignKey("rooms.id", ondelete="CASCADE"), nullable=False,
    )
    student_id:  Mapped[int]      = mapped_column(
        Integer, ForeignKey("students.id", ondelete="CASCADE"), nullable=False,
    )
    slot_number: Mapped[int]      = mapped_column(Integer, nullable=False)
    assigned_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_now_ist)

    room: Mapped[Room] = relationship("Room", back_populates="roommates")
    student: Mapped[Student] = relationship("Student", back_populates="roommate_slot")


