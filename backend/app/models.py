# Enumerations  (stored as human-readable strings in the DB)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

class HostelType(str, enum.Enum):
    BOYS  = "boys"
    GIRLS = "girls"


class Block(str, enum.Enum):
    A = "A"
    B = "B"
    C = "C"
    D = "D"
    E = "E"
    F = "F"
    G = "G"


class RoomType(str, enum.Enum):
    AC     = "ac"
    NON_AC = "non_ac"


class ReadingSource(str, enum.Enum):
    """
    Source tag applied to every reading — on-screen, in charts, and in PDF reports.
    'Sensor (Future)' is accepted by the schema today; the ESP32 will use it without
    any backend schema changes when hardware integration begins.
    """
    MANUAL    = "Manual Entry"
    SIMULATED = "Simulated Demo Data"
    SENSOR    = "Sensor (Future)"


